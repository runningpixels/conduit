/**
 * `applyBrand` is the entire security boundary for Mode A white-labelling:
 * a hardcoded allowlist of CSS custom-property names, hex-only values, and
 * `setProperty` calls — never a CSS string, never a `<style>` tag, never
 * `innerHTML`. These tests exist to keep that boundary honest under change:
 *
 *   - the allowlist must track the schema (a forgotten new palette key is a
 *     silent no-op for that colour, not a build failure, unless something
 *     asserts completeness);
 *   - only the 18 named properties may ever be touched, no matter what a
 *     config or a hostile cache contains;
 *   - an inline brand palette outranks every stylesheet rule, so it has to
 *     be re-applied per resolved theme or light mode breaks;
 *   - the localStorage cache is a paint cache, not a source of truth, and
 *     has to survive being corrupted or hand-edited without ever reaching
 *     `setProperty` with something that isn't a hex colour.
 */

import { beforeEach, describe, expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { BrandConfig, BrandPalette } from '@conduit/config-schema';
import {
  applyBrand,
  applyBrandPalette,
  applyBrandTheme,
  applyCachedBrand,
  clearBrand,
  clearBrandCache,
  isValidHexColor,
  PALETTE_PROPERTY_MAP,
  readBrandCache,
  writeBrandCache,
} from './applyBrand';
import { appName, brand, resetBrand } from './index';
import { readPalette, writePalette } from '../shell/uiPrefs';

